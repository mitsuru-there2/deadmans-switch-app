// Exactly 256 bits encoded as unpadded Base64URL; randomness is supplied by the OS.
export function encodeOperationSecret(bytes: Uint8Array): string {
  if (bytes.length !== 32) throw new Error("INVALID_OPERATION_SECRET");
  const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";
  let bits = 0,
    value = 0,
    result = "";
  for (const byte of bytes) {
    value = (value << 8) | byte;
    bits += 8;
    while (bits >= 6) {
      bits -= 6;
      result += alphabet[(value >>> bits) & 63];
    }
  }
  if (bits) result += alphabet[(value << (6 - bits)) & 63];
  return result;
}
